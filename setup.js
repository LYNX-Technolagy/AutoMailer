#!/usr/bin/env node
/**
 * First-run setup for AutoMailer.
 * Creates .env with PORT, SESSION_SECRET, and DRY_RUN if it doesn't exist.
 *
 * Usage:  npm run setup
 * Force:  npm run setup -- --force   (overwrites an existing .env)
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const readline = require('readline');

const ENV_PATH = path.join(__dirname, '.env');
const FORCE = process.argv.includes('--force');

const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
const ask = (q) => new Promise((resolve) => rl.question(q, resolve));

function randomSecret() {
  return crypto.randomBytes(32).toString('hex');
}

async function main() {
  console.log('');
  console.log('AutoMailer setup');
  console.log('----------------');
  console.log('');

  if (fs.existsSync(ENV_PATH) && !FORCE) {
    console.log('.env already exists. Nothing to do.');
    console.log('If you want to regenerate it, run: npm run setup -- --force');
    console.log('');
    rl.close();
    return;
  }

  const portAnswer = (await ask('Port to run on [3000]: ')).trim();
  const port = portAnswer === '' ? '3000' : portAnswer;
  if (!/^\d+$/.test(port)) {
    console.error('Port must be a number.');
    rl.close();
    process.exit(1);
  }

  const dryAnswer = (await ask('Enable DRY_RUN (test mode, no emails actually sent)? [y/N]: '))
    .trim()
    .toLowerCase();
  const dryRun = dryAnswer === 'y' || dryAnswer === 'yes' ? 'true' : 'false';

  const sessionSecret = randomSecret();

  const envContent = `# AutoMailer configuration
# Generated by setup.js on ${new Date().toISOString()}
# Safe to edit by hand if needed.

PORT=${port}

# Signs session cookies. Rotating this logs everyone out.
SESSION_SECRET=${sessionSecret}

# When true, sends are simulated — no real email goes out.
# The app's "Connect Gmail" step is skipped in dry-run mode.
DRY_RUN=${dryRun}
`;

  fs.writeFileSync(ENV_PATH, envContent, { mode: 0o600 });

  console.log('');
  console.log('✓ Setup complete.');
  console.log('');
  console.log(`  Start:  npm run dev`);
  console.log('');
  console.log(`  App:    http://localhost:${port}/app     ← use this`);
  console.log(`  Site:   http://localhost:${port}         ← landing page`);
  console.log('');
  console.log('  Open /app, click "Connect Gmail", and follow the instructions.');
  console.log('');

  rl.close();
}

main().catch((err) => {
  console.error('\nSetup failed:', err.message);
  process.exit(1);
});